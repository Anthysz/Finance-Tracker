import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          // Google Identity Services needs the sign-in popup and this page in
          // the same browsing context group so the token can be handed back.
          // Without this, browsers report "Popup window closed".
          {
            key: "Cross-Origin-Opener-Policy",
            value: "same-origin-allow-popups",
          },
        ],
      },
    ];
  },
};

export default nextConfig;
